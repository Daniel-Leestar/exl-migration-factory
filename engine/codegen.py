"""Turn IR into PySpark source code by fixed rules. Same IR in, same text out.
依固定規則把 IR 轉成 PySpark 原始碼;相同的 IR 永遠產出相同的文字。

Every place where SQL Server and Spark behave differently is handled here and
nowhere else, and each rule that fires is recorded so the report can show it.
SQL Server 與 Spark 行為不同之處全部集中在這裡處理,
每條被套用的規則都會記錄下來,供報告顯示。
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from engine import ir
from engine.ir import OutOfScope
from engine.ir_types import Scope, decimal_type, infer, operand_decimal, query_scope, resolve_query, unify
from engine.model import Column, decimal_parts, is_decimal, is_integer

HEADER = '''"""Generated by the rule-based code generator (deterministic). Do not edit by hand."""
from decimal import Decimal

from pyspark.sql import functions as F
'''

# Emitted only when a job divides decimals.
# 只有 job 用到小數相除時才會輸出。
DECIMAL_DIV_HELPER = '''

def tsql_decimal_div(left, right, result_type, scale):
    """Decimal division the SQL Server way: extra digits are cut off, not rounded.

    Spark rounds (2.0 / 3 -> 0.666667); SQL Server truncates (0.666666). Truncate Spark's
    quotient, then step back once if Spark's own rounding had already carried it too far.
    A zero divisor gives NULL.
    """
    step = F.lit(Decimal(1).scaleb(-scale)).cast(f"decimal({scale + 1},{scale})")
    quotient = left / right
    cut = quotient - (quotient % step)
    overshoot = F.abs(cut * right) > F.abs(left)
    cut = F.when(overshoot, cut - F.signum(quotient).cast("decimal(1,0)") * step).otherwise(cut)
    return cut.cast(result_type)
'''

RUN_HEADER = "\n\ndef run(spark, tables):\n"

_SPARK_TYPES = {"int": "int", "bigint": "bigint", "float": "double", "string": "string", "bool": "boolean", "date": "date"}
_PYTHON_OPS = {"=": "==", "<>": "!=", "<": "<", "<=": "<=", ">": ">", ">=": ">="}
_AGG_ALIAS = "__agg"
_SAFE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

RULE_INT_DIVISION = "integer / integer drops the fraction (SQL Server) -> result cast back to a whole number"
RULE_INT_AVG = "AVG over whole numbers drops the fraction (SQL Server) -> SUM / COUNT cast back to a whole number"
RULE_DECIMAL_DIVISION = "decimal division cuts off extra digits instead of rounding (SQL Server) -> exact truncating division"
RULE_TEXT_COMPARE = "text comparison ignores case and trailing spaces (SQL Server default collation) -> compare UPPER(RTRIM(x))"
RULE_TEXT_GROUP = "GROUP BY on text ignores case and trailing spaces -> group by UPPER(RTRIM(x))"
RULE_TEXT_CONCAT = "text + text gives NULL when either side is NULL -> F.concat"
RULE_CONCAT_NULL = "CONCAT() treats NULL as empty text -> coalesce each part to ''"
RULE_LEN = "LEN ignores trailing spaces -> length(rtrim(x))"
RULE_ISNULL = "ISNULL keeps the type of its first argument -> second argument cast to it"
RULE_SUM_TYPE = "SUM keeps SQL Server's result type -> explicit cast"
RULE_TRUNCATE = "ROUND(x, n, 1) cuts off digits instead of rounding -> x - (x % step)"


@dataclass
class Generated:
    code: str
    rules: list[str] = field(default_factory=list)
    output_columns: list[Column] = field(default_factory=list)


def spark_type(type_name: str) -> str:
    if is_decimal(type_name):
        return type_name
    return _SPARK_TYPES[type_name]


def generate(query: ir.Query, catalog: dict[str, list[Column]]) -> Generated:
    """Generate a `run(spark, tables)` function for an IR query.
    為 IR 查詢產生 `run(spark, tables)` 函數。

    `tables` maps table names from the schema file to DataFrames.
    `tables` 是「結構檔中的表名 -> DataFrame」的對應。
    """
    emitter = _Emitter(catalog)
    resolved = resolve_query(query, catalog)
    columns = emitter.query(resolved, "df")
    emitter.lines.append("return df")
    uses_division = RULE_DECIMAL_DIVISION in emitter.rules
    if uses_division:
        # Exact decimal arithmetic needs Spark to keep every digit rather than trim the scale.
        # 精確的小數運算需要 Spark 保留所有位數,而不是自動縮減小數位。
        emitter.lines.insert(0, 'spark.conf.set("spark.sql.decimalOperations.allowPrecisionLoss", "false")')
    body = "\n".join("    " + line for line in emitter.lines)
    code = HEADER + (DECIMAL_DIV_HELPER if uses_division else "") + RUN_HEADER + body + "\n"
    return Generated(code, sorted(emitter.rules), columns)


class _Emitter:
    def __init__(self, catalog):
        self.catalog = catalog
        self.lines: list[str] = []
        self.rules: set[str] = set()
        self.counter = 0

    # ----- query structure / 查詢結構 -----

    def query(self, q: ir.Query, var: str) -> list[Column]:
        scope = query_scope(q, self.catalog)
        self.lines.append(f"{var} = {self.source(q.source)}")
        for join in q.joins:
            self._require_bool(join.on, scope, "JOIN ... ON")
            self.lines.append(f'{var} = {var}.join({self.source(join.source)}, on={self.expr(join.on, scope)}, how="{join.kind}")')
        if q.where is not None:
            self._require_bool(q.where, scope, "WHERE")
            self.lines.append(f"{var} = {var}.where({self.expr(q.where, scope)})")

        select, having = q.select, q.having
        aggregates = _unique(n for o in select for n in ir.walk(o.expr) if isinstance(n, ir.Agg))
        aggregates = _unique(aggregates + [n for n in ir.walk(having) if isinstance(n, ir.Agg)] if having is not None else aggregates)
        if q.group_by or aggregates or having is not None:
            scope, mapping = self.aggregate(q, var, scope, aggregates)
            select = tuple(ir.Output(o.name, ir.substitute(o.expr, mapping)) for o in select)
            having = ir.substitute(having, mapping)
            for item in [o.expr for o in select] + ([having] if having is not None else []):
                for node in ir.walk(item):
                    if isinstance(node, ir.Col) and node.table != _AGG_ALIAS:
                        raise OutOfScope(f"column {ir.show(node)} must appear in GROUP BY or inside an aggregate")
        if having is not None:
            self._require_bool(having, scope, "HAVING")
            self.lines.append(f"{var} = {var}.where({self.expr(having, scope)})")

        columns, parts = [], []
        for output in select:
            type_name = infer(output.expr, scope)
            if type_name == "bool":
                raise OutOfScope(f"output column {output.name} is a bare condition")
            code = self.expr(output.expr, scope)
            if type_name == "null":
                type_name = "int"
            columns.append(Column(output.name, type_name))
            parts.append(f"{code}.alias({output.name!r})")
        self.lines.append(f"{var} = {var}.select(")
        self.lines.extend(f"    {part}," for part in parts)
        self.lines.append(")")
        return columns

    def source(self, source: ir.Source) -> str:
        if source.query is None:
            return f"tables[{source.table!r}].alias({source.alias!r})"
        self.counter += 1
        var = f"sub{self.counter}"
        self.query(source.query, var)
        return f"{var}.alias({source.alias!r})"

    def aggregate(self, q: ir.Query, var: str, scope: Scope, aggregates: list) -> tuple[Scope, dict]:
        """Emit groupBy/agg and return the scope and replacements valid after it.
        輸出 groupBy/agg,並回傳彙總之後適用的欄位範圍與替換表。
        """
        keys, measures, columns, mapping = [], [], [], {}
        for i, key in enumerate(q.group_by):
            type_name = infer(key, scope)
            code = self.expr(key, scope)
            if type_name == "string":
                # Rows whose text differs only by case form one group; show the smallest spelling.
                # 只差大小寫的文字算同一組;顯示時取排序最小的寫法。
                self.rules.add(RULE_TEXT_GROUP)
                keys.append(f'F.upper(F.rtrim({code})).alias("__g{i}")')
                measures.append(f'F.min({code}).alias("__r{i}")')
                name = f"__r{i}"
            else:
                keys.append(f'{code}.alias("__g{i}")')
                name = f"__g{i}"
            columns.append(Column(name, "int" if type_name == "null" else type_name))
            mapping[key] = ir.Col(name, _AGG_ALIAS)
        for i, agg in enumerate(aggregates):
            columns.append(Column(f"__a{i}", infer(agg, scope)))
            measures.append(f'{self.agg(agg, scope)}.alias("__a{i}")')
            mapping[agg] = ir.Col(f"__a{i}", _AGG_ALIAS)
        if not measures:
            measures.append('F.count(F.lit(1)).alias("__n")')
        self.lines.append(f"{var} = {var}.groupBy({', '.join(keys)}).agg(")
        self.lines.extend(f"    {m}," for m in measures)
        self.lines.append(")")
        after = Scope()
        after.add(_AGG_ALIAS, columns)
        return after, mapping

    def agg(self, node: ir.Agg, scope: Scope) -> str:
        result = infer(node, scope)
        if node.arg is None:
            return 'F.count(F.lit(1)).cast("int")'
        arg_type = infer(node.arg, scope)
        arg = self.expr(node.arg, scope)
        if arg_type == "null":
            arg = f'{arg}.cast("int")'
        if node.func == "COUNT":
            if node.distinct:
                if arg_type == "string":
                    self.rules.add(RULE_TEXT_COMPARE)
                    arg = f"F.upper(F.rtrim({arg}))"
                return f'F.countDistinct({arg}).cast("int")'
            return f'F.count({arg}).cast("int")'
        if node.func in ("MIN", "MAX"):
            return f"F.{node.func.lower()}({arg})"
        if node.func == "SUM":
            if result == "float":
                return f"F.sum({arg})"
            self.rules.add(RULE_SUM_TYPE)
            return f'F.sum({arg}).cast("{spark_type(result)}")'
        # AVG
        if result == "float":
            return f"F.avg({arg})"
        if is_integer(result):
            self.rules.add(RULE_INT_AVG)
            return f'(F.sum({arg}) / F.count({arg})).cast("{spark_type(result)}")'
        self.rules.add(RULE_DECIMAL_DIVISION)
        _, scale = decimal_parts(arg_type)
        return f'tsql_decimal_div(F.sum({arg}).cast("decimal(38,{scale})"), F.count({arg}).cast("decimal(10,0)"), "{result}", {decimal_parts(result)[1]})'

    # ----- expressions / 運算式 -----

    def expr(self, node, scope: Scope) -> str:
        if isinstance(node, ir.Col):
            name = node.name if _SAFE_NAME.match(node.name) else f"`{node.name}`"
            return f'F.col("{name}")' if node.table == _AGG_ALIAS else f'F.col("{node.table}.{name}")'
        if isinstance(node, ir.Lit):
            return self.literal(node)
        if isinstance(node, ir.BinOp):
            return self.arithmetic(node, scope)
        if isinstance(node, ir.Cmp):
            return self.compare(node, scope)
        if isinstance(node, ir.Logic):
            for arg in node.args:
                self._require_bool(arg, scope, node.op.upper())
            return "(" + (" & " if node.op == "and" else " | ").join(self.expr(a, scope) for a in node.args) + ")"
        if isinstance(node, ir.Not):
            self._require_bool(node.arg, scope, "NOT")
            return f"(~{self.expr(node.arg, scope)})"
        if isinstance(node, ir.IsNull):
            return f"{self.expr(node.arg, scope)}.{'isNotNull' if node.negated else 'isNull'}()"
        if isinstance(node, ir.InList):
            # x IN (a, b) is the same as x = a OR x = b, including how NULL behaves.
            # x IN (a, b) 等同 x = a OR x = b,連 NULL 的行為都一樣。
            tests = tuple(ir.Cmp("=", node.arg, item) for item in node.items)
            inner = tests[0] if len(tests) == 1 else ir.Logic("or", tests)
            return self.expr(ir.Not(inner) if node.negated else inner, scope)
        if isinstance(node, ir.Like):
            if infer(node.arg, scope) != "string" or "\\" in node.pattern.value:
                raise OutOfScope("LIKE on a non-text value or with a backslash in the pattern")
            self.rules.add(RULE_TEXT_COMPARE)
            code = f"F.upper({self.expr(node.arg, scope)}).like({node.pattern.value.upper()!r})"
            return f"(~{code})" if node.negated else code
        if isinstance(node, ir.Case):
            return self.case(node, scope)
        if isinstance(node, ir.Cast):
            source = infer(node.arg, scope)
            if node.type == "string" and source == "float":
                raise OutOfScope("CAST of a FLOAT to text (the two systems print floats differently)")
            if source == "bool":
                raise OutOfScope("CAST of a condition")
            return f'{self.expr(node.arg, scope)}.cast("{spark_type(node.type)}")'
        if isinstance(node, ir.Func):
            return self.function(node, scope)
        if isinstance(node, ir.Agg):
            raise OutOfScope("aggregate function used where a plain value is expected")
        raise OutOfScope(f"cannot generate code for {type(node).__name__}")

    def literal(self, node: ir.Lit) -> str:
        if node.type == "null":
            return 'F.lit(None).cast("int")'
        if node.type == "int":
            return f"F.lit({int(node.value)})" if -2**31 <= int(node.value) < 2**31 else f'F.lit({int(node.value)}).cast("bigint")'
        if node.type == "decimal":
            return f'F.lit(Decimal("{node.value}")).cast("{infer(node, Scope())}")'
        return f"F.lit({str(node.value)!r})"

    def typed(self, node, scope: Scope, target: str) -> str:
        """Code for `node`, cast to `target` when its own type differs.
        產生 `node` 的程式;型別與 `target` 不同時加上轉型。
        """
        code = self.expr(node, scope)
        return code if infer(node, scope) == target else f'{code}.cast("{spark_type(target)}")'

    def arithmetic(self, node: ir.BinOp, scope: Scope) -> str:
        result = infer(node, scope)
        left, right = self.expr(node.left, scope), self.expr(node.right, scope)
        if result == "string":
            self.rules.add(RULE_TEXT_CONCAT)
            return f"F.concat({left}, {right})"
        if result == "float":
            return f"({left} {node.op} {right})"
        if is_integer(result):
            if node.op == "/":
                self.rules.add(RULE_INT_DIVISION)
                return f'({left} / {right}).cast("{spark_type(result)}")'
            return f'({left} {node.op} {right}).cast("{spark_type(result)}")'
        if node.op == "/":
            self.rules.add(RULE_DECIMAL_DIVISION)
            return f'tsql_decimal_div({self._as_decimal(node.left, scope)}, {self._as_decimal(node.right, scope)}, "{result}", {decimal_parts(result)[1]})'
        return f'({left} {node.op} {right}).cast("{result}")'

    def _as_decimal(self, node, scope: Scope) -> str:
        type_name = infer(node, scope)
        code = self.expr(node, scope)
        if is_decimal(type_name):
            return code
        return f'{code}.cast("{operand_decimal(node, type_name)}")'

    def compare(self, node: ir.Cmp, scope: Scope) -> str:
        types = [infer(node.left, scope), infer(node.right, scope)]
        if "bool" in types:
            raise OutOfScope(f"comparison of a condition in {ir.show(node)}")
        unify(types, node)
        left, right = self.expr(node.left, scope), self.expr(node.right, scope)
        if "string" in types:
            self.rules.add(RULE_TEXT_COMPARE)
            left, right = f"F.upper(F.rtrim({left}))", f"F.upper(F.rtrim({right}))"
        return f"({left} {_PYTHON_OPS[node.op]} {right})"

    def case(self, node: ir.Case, scope: Scope) -> str:
        result = infer(node, scope)
        if result == "bool":
            raise OutOfScope("CASE that returns a condition")
        target = "int" if result == "null" else result
        code = "F"
        for condition, value in node.whens:
            self._require_bool(condition, scope, "CASE WHEN")
            code += f".when({self.expr(condition, scope)}, {self.typed(value, scope, target)})"
        if node.default is not None:
            code += f".otherwise({self.typed(node.default, scope, target)})"
        return code

    def function(self, node: ir.Func, scope: Scope) -> str:
        result = infer(node, scope)
        types = [infer(a, scope) for a in node.args]
        args = [self.expr(a, scope) for a in node.args]
        name = node.name

        def need_text(position: int = 0):
            if types[position] not in ("string", "null"):
                raise OutOfScope(f"{name} applied to a {types[position]} value")

        if name in ("UPPER", "LOWER", "LTRIM", "RTRIM", "TRIM"):
            need_text()
            return f"F.{name.lower()}({args[0]})"
        if name == "LEN":
            need_text()
            self.rules.add(RULE_LEN)
            return f"F.length(F.rtrim({args[0]}))"
        if name == "SUBSTRING":
            need_text()
            return f"{args[0]}.substr({args[1]}, {args[2]})"
        if name == "LEFT":
            need_text()
            return f"{args[0]}.substr(F.lit(1), {args[1]})"
        if name == "RIGHT":
            need_text()
            return f"F.right({args[0]}, {args[1]})"
        if name == "REPLACE":
            for position in range(3):
                need_text(position)
            return f"F.replace({args[0]}, {args[1]}, {args[2]})"
        if name == "CONCAT":
            if "float" in types:
                raise OutOfScope("CONCAT of a FLOAT value (the two systems print floats differently)")
            self.rules.add(RULE_CONCAT_NULL)
            parts = [f'F.coalesce({a}.cast("string"), F.lit(""))' for a in args]
            return f"F.concat({', '.join(parts)})"
        if name in ("COALESCE", "ISNULL"):
            if name == "ISNULL":
                self.rules.add(RULE_ISNULL)
            target = "int" if result == "null" else result
            return f"F.coalesce({', '.join(self.typed(a, scope, target) for a in node.args)})"
        if name == "NULLIF":
            test = self.compare(ir.Cmp("=", node.args[0], node.args[1]), scope)
            return f'F.when({test}, F.lit(None).cast("{spark_type(result)}")).otherwise({args[0]})'
        if name in ("ABS", "ROUND", "TRUNCATE") and result in ("string", "bool", "date"):
            raise OutOfScope(f"{name} applied to a {result} value")
        if name == "ABS":
            return f"F.abs({args[0]})"
        if name in ("ROUND", "TRUNCATE"):
            digits = int(node.args[1].value)
            if is_integer(result):
                if digits < 0:
                    raise OutOfScope("ROUND of a whole number to a negative number of digits")
                return args[0]
            if name == "ROUND":
                return f"F.round({args[0]}, {digits})" if result == "float" else f'F.round({args[0]}, {digits}).cast("{result}")'
            if digits < 0:
                raise OutOfScope("truncating ROUND with a negative number of digits")
            self.rules.add(RULE_TRUNCATE)
            step = "1" if digits == 0 else "0." + "0" * (digits - 1) + "1"
            return f'({args[0]} - ({args[0]} % F.lit(Decimal("{step}")).cast("{decimal_type(digits + 1, digits)}"))).cast("{result}")'
        raise OutOfScope(f"function {name} is not supported")

    def _require_bool(self, node, scope: Scope, where: str) -> None:
        if infer(node, scope) != "bool":
            raise OutOfScope(f"{where} needs a condition but got {ir.show(node)}")


def _unique(items) -> list:
    seen, ordered = set(), []
    for item in items:
        if item not in seen:
            seen.add(item)
            ordered.append(item)
    return ordered
