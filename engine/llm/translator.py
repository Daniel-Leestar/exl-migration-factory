"""Ask a language model to translate legacy code the rules cannot handle, and to fix it.
請語言模型翻譯規則處理不了的舊程式,並在失敗時修正。

The model only ever sees: the legacy code, table structures, and made-up rows.
Real data rows are refused here in code, not by convention.
模型只會看到:舊程式、表結構、虛構的資料列。
真實資料列在這裡由程式直接擋下,不是靠約定。
"""
from __future__ import annotations

import datetime as dt
import json
import re
from decimal import Decimal

from engine.job import Job
from engine.llm.client import LLMClient, LLMError
from engine.model import Column, Table

AI_BANNER = '"""AI-GENERATED by {model}. Passed or failed reconciliation as recorded in the report; review before use."""\n'

SYSTEM_PROMPT = """You migrate legacy data jobs (SQL Server T-SQL or SAS) to PySpark.
Reply with exactly one ```python code block and nothing else.

Rules for the code:
- Define exactly one function: def run(spark, tables):
- `tables` is a dict of input DataFrames keyed by table name. Return one DataFrame.
- Allowed imports: `from pyspark.sql import functions as F`, `from pyspark.sql import Window`, `from decimal import Decimal`.
- Do not read or write files, do not call spark.read / spark.sql on files, do not define Python UDFs.
- The output column names must match the legacy job exactly. Row order does not matter.

SQL Server behaviour you must reproduce:
- integer / integer drops the fraction (7 / 2 = 3); AVG of an integer column also drops the fraction.
- Text comparison, JOIN and GROUP BY on text ignore upper/lower case and trailing spaces.
- SUM over no rows is NULL; COUNT over no rows is 0.
- ISNULL(a, b) returns b when a is NULL and keeps a's type.
- RANK() leaves gaps after ties; DENSE_RANK() does not.

SAS behaviour you must reproduce:
- A missing numeric value sorts before every number and counts as smaller than any number.
- FIRST.x / LAST.x mark the first / last row of each BY group after sorting.
- RETAIN carries a value from one row to the next; translate it with a Spark window.
- PROC MEANS ignores missing values."""


def translate(job: Job, schemas: dict[str, list[Column]], client: LLMClient,
              output_columns: list[Column] | None = None) -> str:
    """First translation of a legacy job. Returns Python source.
    舊 job 的第一次翻譯,回傳 Python 原始碼。
    """
    prompt = "\n\n".join(filter(None, [
        f"Translate this legacy {_language(job)} job to PySpark.",
        _schema_text(schemas),
        _output_text(output_columns),
        f"Legacy code:\n```\n{job.legacy_code.strip()}\n```",
    ]))
    return _finish(client.complete(SYSTEM_PROMPT, prompt), client)


def repair(job: Job, schemas: dict[str, list[Column]], code: str, problem: str, client: LLMClient,
           output_columns: list[Column] | None = None) -> str:
    """Ask for a corrected translation given what went wrong. Returns Python source.
    提供出錯情況,請模型給出修正後的翻譯,回傳 Python 原始碼。
    """
    prompt = "\n\n".join(filter(None, [
        f"Your PySpark translation of this legacy {_language(job)} job is wrong. Fix it.",
        _schema_text(schemas),
        _output_text(output_columns),
        f"Legacy code:\n```\n{job.legacy_code.strip()}\n```",
        f"Your current translation:\n```python\n{code.strip()}\n```",
        f"What went wrong:\n{problem}",
        "Reply with the complete corrected code.",
    ]))
    return _finish(client.complete(SYSTEM_PROMPT, prompt), client)


def describe_failure(inputs: dict[str, Table], legacy: Table, new: Table, report: dict) -> str:
    """Describe a mismatch for the model. Row values are included only for synthetic data.
    為模型描述一次不一致;只有合成資料才會附上資料列的值。
    """
    checks = report["checks"]
    summary = (
        f"Row count: legacy {checks['row_count']['legacy']}, yours {checks['row_count']['new']}. "
        f"Rows missing from yours: {checks['rows']['missing']}; extra rows in yours: {checks['rows']['extra']}; "
        f"rows with different values: {checks['rows']['different']}."
    )
    if not checks["schema"]["ok"]:
        summary += (
            f" Columns missing from yours: {checks['schema']['missing_in_new']};"
            f" unexpected columns in yours: {checks['schema']['extra_in_new']}."
        )
    everything = list(inputs.values()) + [legacy, new]
    if not all(t.synthetic for t in everything):
        # Hard stop: values from real data never go into a prompt.
        # 硬性規定:真實資料的值絕不放進 prompt。
        columns = sorted({c["column"] for d in report["samples"]["different"] for c in d["cells"]})
        return summary + (f" Columns whose values differ: {columns}." if columns else "") + \
            " (Row values are withheld because this run used non-synthetic data.)"
    parts = [summary, "Inputs that reproduce the problem (made-up data):"]
    parts += [f"{name}:\n{_table_text(table)}" for name, table in sorted(inputs.items())]
    parts += [f"Expected output (legacy system):\n{_table_text(legacy)}", f"Your output:\n{_table_text(new)}"]
    return "\n\n".join(parts)


def extract_code(answer: str) -> str:
    """Pull the Python source out of a model answer.
    從模型的回答中取出 Python 原始碼。
    """
    blocks = re.findall(r"```(?:python|py)?\s*\n(.*?)```", answer, flags=re.DOTALL | re.IGNORECASE)
    candidates = [b for b in blocks if "def run" in b] or blocks
    code = candidates[-1] if candidates else (answer if "def run" in answer else "")
    if "def run" not in code:
        raise LLMError("the model's answer contains no `def run(spark, tables)` function")
    return code.strip() + "\n"


def _finish(answer: str, client: LLMClient) -> str:
    return AI_BANNER.format(model=client.model) + extract_code(answer)


def _language(job: Job) -> str:
    return "SAS" if job.language == "sas" else "SQL Server T-SQL"


def _schema_text(schemas: dict[str, list[Column]]) -> str:
    lines = ["Input tables (keys of `tables`):"]
    lines += [f"- {name}: " + ", ".join(f"{c.name} {c.type}" for c in columns) for name, columns in sorted(schemas.items())]
    return "\n".join(lines)


def _output_text(columns: list[Column] | None) -> str:
    if not columns:
        return ""
    return "The output must have exactly these columns: " + ", ".join(f"{c.name} ({c.type})" for c in columns)


def _table_text(table: Table, limit: int = 30) -> str:
    def cell(value):
        if isinstance(value, (Decimal, dt.date)):
            return str(value)
        return value

    lines = [json.dumps([c.name for c in table.columns])]
    lines += [json.dumps([cell(v) for v in row], ensure_ascii=False) for row in table.rows[:limit]]
    if len(table.rows) > limit:
        lines.append(f"... ({len(table.rows) - limit} more rows)")
    return "\n".join(lines) if table.rows else lines[0] + "\n(no rows)"
